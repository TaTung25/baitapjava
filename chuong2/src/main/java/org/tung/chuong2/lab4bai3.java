    private boolean soNT(int i) {
        if (i<2) {
            return false;
        }
        if (i==2) {
            return true;
        }
        if (i%2==0) {
            return false;
        }
        for (int n=3; n<=Math.sqrt(i);n+=2) {
            if (i%n==0) {
                return false;
            }
        }return true;
    }
