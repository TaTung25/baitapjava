    public void tinhTong(){
        int n;
        try {
            n = Integer.parseInt(txtxt1.getText().trim());
            if (n<=2) {
                JOptionPane.showMessageDialog(this, "N phai lon hon 2");
                return;
            }
        }catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Vui long nhap so hop le");
            return;
        }
        btinh.setEnabled(false);
        tT.setValue(0);
        jLabel2.setText("Dang tinh...");
        
        SwingWorker<Long, Void> worker = new SwingWorker<>() {
            @Override   
            protected Long doInBackground() {
                long sum = 0;
                for (int i = 2; i<n; i++) {
                    if (soNT(i)){
                        sum += i;
                    }
                    int tdo = (int) ((i*100.0)/n);
                    setProgress(tdo);
                }
                return sum;
            }
            @Override
            protected void done() {
                try {
                    long result = get();
                    jLabel2.setText("Tong cac so nguyen nho hon" + n +"="+result);
                }catch (Exception e){
                    jLabel2.setText("co loi khi tinh.");
                }
                btinh.setEnabled(true);
                tT.setValue(100);
            }
        };
        worker.addPropertyChangeListener(evt -> {
           if ("progress".equals(evt.getPropertyName())) {
               tT.setValue((int) evt.getNewValue());
           } 
        });
        worker.execute();
    }          

